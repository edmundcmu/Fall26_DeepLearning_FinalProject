"""Reproduce validation plots from the saved predictions and original val extxyz."""
import argparse
import json
from pathlib import Path
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from ase.io import read

p = argparse.ArgumentParser()
p.add_argument('--validation-data', required=True, help='Path to original validation structures.extxyz')
args = p.parse_args()
root = Path(__file__).resolve().parents[1]
out = root / 'analysis'
frames = read(args.validation_data, ':')
ids = np.array([int(a.info['source_index']) for a in frames])
species = np.concatenate([a.numbers for a in frames])
dft_energy = np.array([a.get_potential_energy() for a in frames])
dft_force = np.concatenate([a.get_forces(apply_constraint=False) for a in frames])
paths = {'U0': root/'reference/u0_predictions.npz', 'Full LoRA': root/'reference/val_predictions.npz', 'Random LoRA': root/'training/runs/random/seed41_mask41/val_predictions.npz'}
colors = {'U0':'#6d7480', 'Full LoRA':'#2367a3', 'Random LoRA':'#db7132'}
pred = {}
for name, path in paths.items():
    with np.load(path) as f:
        assert np.array_equal(ids, f['source_index']), f'Frame ordering mismatch in {path}'
        pred[name] = {k: f[k].copy() for k in f.files}
cal = json.loads((root/'training/runs/lall/calibration.json').read_text())
print('Calibration keys:', list(cal))
# Use reported metrics generated by the same evaluation routine and fixed U0 calibration.
random_metrics = json.loads((root/'training/runs/random/seed41_mask41/validation_metrics.json').read_text())
full_metrics = json.loads((root/'reference/validation_metrics.json').read_text())
metrics = {'U0':random_metrics['U0'], 'Full LoRA':full_metrics['L_All'], 'Random LoRA':random_metrics['L_Random']}
keys = ['energy_raw_MAE_eV','energy_aligned_MAE_eV','H_force_component_MAE_eV_per_A','Cu_force_component_MAE_eV_per_A']
titles = ['Raw energy', 'Aligned energy', 'H force components', 'Cu force components']
fig, axes = plt.subplots(1,4,figsize=(12.5,3.5),layout='constrained')
for ax,key,title in zip(axes,keys,titles):
    vals=[metrics[n][key] for n in metrics]
    bars=ax.bar(range(3), vals, color=[colors[n] for n in metrics])
    ax.bar_label(bars,fmt='%.4f',padding=3,fontsize=8)
    ax.set_title(title); ax.set_xticks(range(3),['U0','Full','Random'],rotation=20)
    ax.set_ylabel('MAE (eV/config)' if 'energy' in key else 'MAE (eV/Å)')
    ax.set_ylim(0,max(vals)*1.23); ax.spines[['top','right']].set_visible(False)
fig.suptitle('Validation error on 100 configurations')
fig.savefig(out/'01_validation_metrics.png',dpi=200); plt.close(fig)
fig,ax=plt.subplots(figsize=(7,4.2),layout='constrained')
for label,path in [('Full LoRA',root/'reference/training.jsonl'),('Random LoRA',root/'training/runs/random/seed41_mask41/training.jsonl')]:
    records=[json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    vals=[r for r in records if 'val_loss' in r]
    ax.plot([r['step'] for r in vals],[r['val_loss'] for r in vals],marker='o',label=label,color=colors[label])
ax.set(xlabel='Optimizer updates',ylabel='Normalized validation loss',title='Checkpoint selection on the validation set'); ax.legend(); ax.grid(alpha=.25)
fig.savefig(out/'02_validation_convergence.png',dpi=200); plt.close(fig)
fig,axes=plt.subplots(2,3,figsize=(12,7),layout='constrained')
for j,(name,values) in enumerate(pred.items()):
    for i,(mask,element) in enumerate([(species==1,'H'),(species==29,'Cu')]):
        x=dft_force[mask].ravel(); y=values['forces'][mask].ravel()
        ax=axes[i,j]; ax.scatter(x,y,s=5,alpha=.25,color=colors[name],rasterized=True)
        lo=min(x.min(),y.min()); hi=max(x.max(),y.max()); ax.plot([lo,hi],[lo,hi],color='black',lw=.8)
        ax.set_title(f'{name} · {element}'); ax.set_xlabel('DFT force (eV/Å)'); ax.set_ylabel('Predicted force (eV/Å)')
fig.suptitle('Force component parity'); fig.savefig(out/'03_force_parity.png',dpi=200); plt.close(fig)
fig,axes=plt.subplots(1,2,figsize=(10,4),layout='constrained')
for ax,(mask,element) in zip(axes,[(species==1,'H'),(species==29,'Cu')]):
    for name,values in pred.items():
        residual=np.abs(values['forces'][mask]-dft_force[mask]).ravel()
        xx=np.sort(residual); yy=np.arange(1,len(xx)+1)/len(xx)
        ax.plot(xx,yy,label=name,color=colors[name])
    ax.set(xlabel='Absolute component error (eV/Å)',ylabel='Fraction of components',title=element, xlim=(0,np.quantile(np.abs(pred['U0']['forces'][mask]-dft_force[mask]),.99)))
    ax.grid(alpha=.2)
axes[0].legend(); fig.suptitle('Force error distributions'); fig.savefig(out/'04_force_error_cdf.png',dpi=200); plt.close(fig)
(out/'comparison_metrics.json').write_text(json.dumps(metrics,indent=2)+'\n')
print(json.dumps(metrics,indent=2))
